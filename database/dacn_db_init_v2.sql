-- ============================================================================
-- DACN | LIS -> Integration (FHIR R4) -> EMR
-- Database: dacn_db | PostgreSQL 18 (compatible with recent PostgreSQL)
-- 1 script: 3 schemas / 13 tables / internal FK, unique and CHECK / extended smoke tests
-- Design basis: 20261012_Implementation_DACN_v2, section 6 and 9.
--
-- HOW TO RUN
-- 1) pgAdmin 4 -> Databases -> dacn_db -> Query Tool
-- 2) Open this .sql file and Execute Script (F5).
-- 3) End of file should show counts: lis=5, integration=5, emr=3.
--
-- SAFE RE-RUN: CREATE ... IF NOT EXISTS skips tables already present.
-- IMPORTANT: IF NOT EXISTS does NOT compare/upgrade a previously created table.
-- Existing lis.patients from earlier instructions has the same columns/constraints.
-- NO DROP, TRUNCATE, or production-destructive reset in this script.
-- IDs and hash values must be generated by the application; no FHIR server needed.
-- ============================================================================

BEGIN;
DO $database_guard$
BEGIN
    IF current_database() <> 'dacn_db' THEN
        RAISE EXCEPTION 'You are connected to database %, not dacn_db', current_database();
    END IF;
END
$database_guard$;

CREATE SCHEMA IF NOT EXISTS lis;
CREATE SCHEMA IF NOT EXISTS integration;
CREATE SCHEMA IF NOT EXISTS emr;

-- ============================================================================
-- 1. LIS (5 tables)
-- ============================================================================

CREATE TABLE IF NOT EXISTS lis.patients (
    patient_id         TEXT PRIMARY KEY,
    source_subject_id  TEXT NOT NULL UNIQUE,
    display_label      TEXT
);

CREATE TABLE IF NOT EXISTS lis.test_catalog (
    test_code          TEXT PRIMARY KEY,
    test_name          TEXT NOT NULL,
    fluid              TEXT,
    category           TEXT,
    accepted_units     JSONB NOT NULL,
    catalog_version    TEXT NOT NULL,
    CONSTRAINT lis_catalog_units_array_chk
        CHECK (jsonb_typeof(accepted_units) = 'array' AND jsonb_array_length(accepted_units) > 0)
);

CREATE TABLE IF NOT EXISTS lis.results (
    result_id          TEXT PRIMARY KEY,
    patient_id         TEXT NOT NULL,
    test_code          TEXT NOT NULL,
    value_num          NUMERIC NOT NULL,
    unit               TEXT NOT NULL,
    reference_low      NUMERIC,
    reference_high     NUMERIC,
    effective_at       TIMESTAMPTZ NOT NULL,
    result_status      TEXT NOT NULL,
    provenance         JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT lis_results_patient_fk FOREIGN KEY (patient_id)
        REFERENCES lis.patients(patient_id),
    CONSTRAINT lis_results_test_fk FOREIGN KEY (test_code)
        REFERENCES lis.test_catalog(test_code),
    CONSTRAINT lis_results_range_chk CHECK (
        reference_low IS NULL OR reference_high IS NULL OR reference_low <= reference_high
    ),
    CONSTRAINT lis_results_status_chk CHECK (result_status IN ('READY', 'FINAL')),
    CONSTRAINT lis_results_provenance_object_chk CHECK (jsonb_typeof(provenance) = 'object')
);

CREATE TABLE IF NOT EXISTS lis.publish_events (
    event_id                  UUID PRIMARY KEY,
    result_id                 TEXT NOT NULL UNIQUE,
    source_system             TEXT NOT NULL,
    source_snapshot           JSONB NOT NULL,
    source_hash               TEXT NOT NULL,
    published_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    exchange_id               UUID, -- external middleware ID; intentionally NO FK
    dispatch_status           TEXT NOT NULL DEFAULT 'PENDING',
    dispatch_attempt_count    INTEGER NOT NULL DEFAULT 0,
    next_retry_at             TIMESTAMPTZ,
    lease_until               TIMESTAMPTZ,
    acked_at                  TIMESTAMPTZ,
    lease_token               UUID,
    last_error_code           TEXT,
    last_error_message        TEXT,
    ack_response              JSONB,
    CONSTRAINT lis_publish_result_fk FOREIGN KEY (result_id)
        REFERENCES lis.results(result_id),
    CONSTRAINT lis_publish_status_chk CHECK (
        dispatch_status IN ('PENDING', 'IN_FLIGHT', 'RETRY_WAIT', 'ACK', 'BLOCKED', 'FAILED')
    ),
    CONSTRAINT lis_publish_attempt_count_chk CHECK (dispatch_attempt_count >= 0),
    CONSTRAINT lis_publish_snapshot_object_chk CHECK (jsonb_typeof(source_snapshot) = 'object'),
    CONSTRAINT lis_publish_ack_chk CHECK (
        dispatch_status <> 'ACK' OR
        (exchange_id IS NOT NULL AND acked_at IS NOT NULL AND ack_response IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS lis.dispatch_attempts (
    dispatch_attempt_id   UUID PRIMARY KEY,
    event_id              UUID NOT NULL,
    attempt_no            INTEGER NOT NULL,
    lease_token           UUID,
    started_at            TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    sent_at               TIMESTAMPTZ,
    response_at           TIMESTAMPTZ,
    ended_at              TIMESTAMPTZ,
    http_status           INTEGER,
    response_body         JSONB,
    error_code            TEXT,
    error_message         TEXT,
    CONSTRAINT lis_attempt_event_fk FOREIGN KEY (event_id)
        REFERENCES lis.publish_events(event_id),
    CONSTRAINT lis_attempt_no_chk CHECK (attempt_no > 0),
    CONSTRAINT lis_attempt_http_chk CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    CONSTRAINT lis_attempt_event_number_uk UNIQUE (event_id, attempt_no)
);

-- ============================================================================
-- 2. INTEGRATION (5 tables)
-- ============================================================================

CREATE TABLE IF NOT EXISTS integration.exchange_transactions (
    exchange_id              UUID PRIMARY KEY,
    event_id                 UUID NOT NULL UNIQUE, -- LIS event ID; NO cross-schema FK
    source_system            TEXT NOT NULL,
    source_result_id         TEXT NOT NULL, -- LIS result ID; NO cross-schema FK
    patient_identifier       JSONB,
    source_payload           JSONB NOT NULL,
    fhir_payload             JSONB,
    source_hash              TEXT NOT NULL,
    payload_hash             TEXT,
    mapping_version          TEXT,
    status                   TEXT NOT NULL DEFAULT 'RECEIVED',
    retry_phase              TEXT,
    next_retry_at            TIMESTAMPTZ,
    lease_until              TIMESTAMPTZ,
    lease_token              UUID,
    send_attempt_count       INTEGER NOT NULL DEFAULT 0,
    verify_attempt_count     INTEGER NOT NULL DEFAULT 0,
    published_at             TIMESTAMPTZ,
    received_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    validated_at             TIMESTAMPTZ,
    mapping_started_at       TIMESTAMPTZ,
    transformed_at           TIMESTAMPTZ,
    first_sent_at            TIMESTAMPTZ,
    target_stored_at         TIMESTAMPTZ,
    verified_at              TIMESTAMPTZ,
    completed_at             TIMESTAMPTZ,
    CONSTRAINT exchange_source_result_uk UNIQUE (source_system, source_result_id),
    CONSTRAINT exchange_status_chk CHECK (
        status IN ('RECEIVED', 'PROCESSING', 'VERIFYING', 'RETRY_WAIT',
                   'DELIVERED', 'REJECTED', 'FAILED')
    ),
    CONSTRAINT exchange_retry_phase_chk CHECK (retry_phase IS NULL OR retry_phase IN ('SEND','VERIFY')),
    CONSTRAINT exchange_retry_wait_chk CHECK (status <> 'RETRY_WAIT' OR retry_phase IS NOT NULL),
    CONSTRAINT exchange_attempt_counters_chk CHECK (
        send_attempt_count >= 0 AND verify_attempt_count >= 0
    ),
    CONSTRAINT exchange_completed_chk CHECK (
        (
            status = 'DELIVERED'
            AND verified_at IS NOT NULL
            AND completed_at IS NOT NULL
        )
        OR
        (
            status <> 'DELIVERED'
            AND completed_at IS NULL
        )
    ),
    CONSTRAINT exchange_source_payload_object_chk CHECK (jsonb_typeof(source_payload) = 'object'),
    CONSTRAINT exchange_fhir_payload_object_chk CHECK (
        fhir_payload IS NULL OR jsonb_typeof(fhir_payload) = 'object'
    )
);

CREATE TABLE IF NOT EXISTS integration.exchange_attempts (
    attempt_id           UUID PRIMARY KEY,
    exchange_id          UUID NOT NULL,
    attempt_no           INTEGER NOT NULL,
    phase                TEXT NOT NULL,
    started_at           TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    sent_at              TIMESTAMPTZ,
    response_at          TIMESTAMPTZ,
    ended_at             TIMESTAMPTZ,
    http_status          INTEGER,
    response_body        JSONB,
    error_code           TEXT,
    error_message        TEXT,
    CONSTRAINT exchange_attempt_transaction_fk FOREIGN KEY (exchange_id)
        REFERENCES integration.exchange_transactions(exchange_id),
    CONSTRAINT exchange_attempt_phase_chk CHECK (phase IN ('SEND', 'VERIFY')),
    CONSTRAINT exchange_attempt_no_chk CHECK (attempt_no > 0),
    CONSTRAINT exchange_attempt_http_chk CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    CONSTRAINT exchange_attempt_phase_number_uk UNIQUE (exchange_id, phase, attempt_no),
    -- Helps ensure exchange_events never associates an attempt with the wrong exchange.
    CONSTRAINT exchange_attempt_id_exchange_uk UNIQUE (attempt_id, exchange_id)
);

CREATE TABLE IF NOT EXISTS integration.exchange_events (
    log_event_id         UUID PRIMARY KEY,
    exchange_id          UUID NOT NULL,
    event_type           TEXT NOT NULL,
    old_status           TEXT,
    new_status           TEXT,
    occurred_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    attempt_id           UUID,
    detail               JSONB,
    CONSTRAINT exchange_event_transaction_fk FOREIGN KEY (exchange_id)
        REFERENCES integration.exchange_transactions(exchange_id),
    CONSTRAINT exchange_event_attempt_same_exchange_fk FOREIGN KEY (attempt_id, exchange_id)
        REFERENCES integration.exchange_attempts(attempt_id, exchange_id)
);

CREATE TABLE IF NOT EXISTS integration.experiment_runs (
    run_id              UUID PRIMARY KEY,
    scenario_id         TEXT NOT NULL,
    protocol_version    TEXT NOT NULL,
    manifest_hash       TEXT NOT NULL,
    git_commit          TEXT,
    environment         JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    ended_at            TIMESTAMPTZ,
    outcome             TEXT,
    artifact_path       TEXT,
    CONSTRAINT experiment_environment_object_chk CHECK (jsonb_typeof(environment) = 'object')
);

CREATE TABLE IF NOT EXISTS integration.field_comparisons (
    comparison_id       UUID PRIMARY KEY,
    run_id              UUID NOT NULL,
    case_id             TEXT NOT NULL,
    exchange_id         UUID, -- nullable if rejected before an exchange exists
    rule_id             TEXT NOT NULL,
    field_path          TEXT NOT NULL,
    expected            JSONB,
    actual_fhir         JSONB,
    actual_target       JSONB,
    outcome             TEXT NOT NULL,
    reason              TEXT,
    CONSTRAINT field_comparison_run_fk FOREIGN KEY (run_id)
        REFERENCES integration.experiment_runs(run_id),
    CONSTRAINT field_comparison_exchange_fk FOREIGN KEY (exchange_id)
        REFERENCES integration.exchange_transactions(exchange_id)
);

-- ============================================================================
-- 3. EMR (3 tables)
-- ============================================================================

CREATE TABLE IF NOT EXISTS emr.patients (
    patient_key       UUID PRIMARY KEY,
    display_label     TEXT
);

CREATE TABLE IF NOT EXISTS emr.patient_links (
    identifier_system  TEXT NOT NULL,
    identifier_value   TEXT NOT NULL,
    patient_key        UUID NOT NULL,
    CONSTRAINT emr_patient_links_pk PRIMARY KEY (identifier_system, identifier_value),
    CONSTRAINT emr_patient_links_patient_fk FOREIGN KEY (patient_key)
        REFERENCES emr.patients(patient_key)
);

CREATE TABLE IF NOT EXISTS emr.lab_results (
    target_id          UUID PRIMARY KEY,
    patient_key        UUID NOT NULL,
    external_system    TEXT NOT NULL,
    external_id        TEXT NOT NULL,
    analyte_system     TEXT NOT NULL,
    analyte_code       TEXT NOT NULL,
    analyte_display    TEXT,
    analyte_context    TEXT,
    quantity           NUMERIC NOT NULL,
    unit_text          TEXT NOT NULL,
    low                NUMERIC,
    high               NUMERIC,
    effective_at       TIMESTAMPTZ NOT NULL,
    clinical_status    TEXT NOT NULL,
    fhir_json          JSONB NOT NULL,
    received_at        TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    stored_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT emr_lab_patient_fk FOREIGN KEY (patient_key)
        REFERENCES emr.patients(patient_key),
    CONSTRAINT emr_lab_external_uk UNIQUE (external_system, external_id),
    CONSTRAINT emr_lab_range_chk CHECK (low IS NULL OR high IS NULL OR low <= high),
    CONSTRAINT emr_lab_status_chk CHECK (clinical_status = 'final'),
    CONSTRAINT emr_lab_fhir_object_chk CHECK (jsonb_typeof(fhir_json) = 'object')
);

-- Indexes support dispatcher/worker selection and frequent joins.
CREATE INDEX IF NOT EXISTS idx_lis_publish_dispatch
    ON lis.publish_events(dispatch_status, next_retry_at);
CREATE INDEX IF NOT EXISTS idx_lis_attempts_event
    ON lis.dispatch_attempts(event_id);
CREATE INDEX IF NOT EXISTS idx_lis_results_patient
    ON lis.results(patient_id);
CREATE INDEX IF NOT EXISTS idx_exchange_status_retry
    ON integration.exchange_transactions(status, next_retry_at);
CREATE INDEX IF NOT EXISTS idx_exchange_events_transaction
    ON integration.exchange_events(exchange_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_emr_lab_patient
    ON emr.lab_results(patient_key);

COMMIT;

-- ============================================================================
-- 4. SMOKE TESTS (inside a transaction that is ROLLED BACK)
--    These tests verify FK, duplicate protection and patient linking.
--    No temporary test rows are kept.
-- ============================================================================
BEGIN;
DO $smoke_tests$
DECLARE
    t           TEXT := '_SMOKE_' || replace(gen_random_uuid()::text, '-', '');
    patient_1   UUID := gen_random_uuid();
    patient_2   UUID := gen_random_uuid();
    event_1     UUID := gen_random_uuid();
    exchange_1  UUID := gen_random_uuid();
    exchange_2  UUID := gen_random_uuid();
    attempt_1   UUID := gen_random_uuid();
    attempt_2   UUID := gen_random_uuid();
    run_1       UUID := gen_random_uuid();
BEGIN
    INSERT INTO lis.patients(patient_id, source_subject_id, display_label)
    VALUES (t, t, 'test only');
    INSERT INTO lis.test_catalog(test_code, test_name, accepted_units, catalog_version)
    VALUES (t, 'test only', '["mg/dL"]'::jsonb, 'smoke-test');
    INSERT INTO lis.results(result_id, patient_id, test_code, value_num, unit,
                            effective_at, result_status, provenance)
    VALUES (t, t, t, -2.5, 'mg/dL', now(), 'FINAL', '{}'::jsonb);

    -- UNIQUE(source_subject_id) must reject duplicate source patient IDs.
    BEGIN
        INSERT INTO lis.patients(patient_id, source_subject_id) VALUES (t || '_dup', t);
        RAISE EXCEPTION 'TEST FAILED: duplicate LIS source patient accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: LIS source_subject_id UNIQUE';
    END;

    -- FK(patient_id) must reject a result for an unknown LIS patient.
    BEGIN
        INSERT INTO lis.results(result_id, patient_id, test_code, value_num, unit,
                                effective_at, result_status)
        VALUES (t || '_orphan', t || '_not_found', t, 1, 'mg/dL', now(), 'FINAL');
        RAISE EXCEPTION 'TEST FAILED: orphan LIS result accepted';
    EXCEPTION WHEN foreign_key_violation THEN
        RAISE NOTICE 'PASS: LIS results -> LIS patients FK';
    END;

    INSERT INTO lis.publish_events(event_id, result_id, source_system, source_snapshot,
                                   source_hash, dispatch_status)
    VALUES (event_1, t, 'https://example.org/lis/result',
            jsonb_build_object('result_id', t), repeat('a', 64), 'PENDING');

    -- UNIQUE(result_id) makes a published result idempotent.
    BEGIN
        INSERT INTO lis.publish_events(event_id, result_id, source_system,
                                       source_snapshot, source_hash)
        VALUES (gen_random_uuid(), t, 'https://example.org/lis/result',
                jsonb_build_object('result_id', t), repeat('a', 64));
        RAISE EXCEPTION 'TEST FAILED: duplicate Publish accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: LIS publish_events.result_id UNIQUE';
    END;

    INSERT INTO emr.patients(patient_key, display_label)
    VALUES (patient_1, 'test one'), (patient_2, 'test two');
    INSERT INTO emr.patient_links(identifier_system, identifier_value, patient_key)
    VALUES ('https://example.org/lis/patient', t, patient_1);

    -- The same external patient identity cannot point to another patient.
    BEGIN
        INSERT INTO emr.patient_links(identifier_system, identifier_value, patient_key)
        VALUES ('https://example.org/lis/patient', t, patient_2);
        RAISE EXCEPTION 'TEST FAILED: ambiguous patient link accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: EMR patient_links composite PK (one-to-one lookup per identifier)';
    END;

    INSERT INTO emr.lab_results(target_id, patient_key, external_system, external_id,
                                analyte_system, analyte_code, quantity, unit_text,
                                effective_at, clinical_status, fhir_json)
    VALUES (gen_random_uuid(), patient_1, 'https://example.org/lis/result', t,
            'https://example.org/lis/test-code', t, 0, 'mg/dL', now(), 'final', '{}'::jsonb);

    -- UNIQUE(external_system, external_id) protects against duplicate result storage.
    BEGIN
        INSERT INTO emr.lab_results(target_id, patient_key, external_system, external_id,
                                    analyte_system, analyte_code, quantity, unit_text,
                                    effective_at, clinical_status, fhir_json)
        VALUES (gen_random_uuid(), patient_1, 'https://example.org/lis/result', t,
                'https://example.org/lis/test-code', t, 99, 'mg/dL', now(), 'final', '{}'::jsonb);
        RAISE EXCEPTION 'TEST FAILED: duplicate EMR source result accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: EMR lab_results(external_system, external_id) UNIQUE';
    END;

    -- Integration: one source result/event should generate at most one transaction.
    INSERT INTO integration.exchange_transactions (
        exchange_id, event_id, source_system, source_result_id, source_payload, source_hash
    ) VALUES (
        exchange_1, event_1, 'https://example.org/lis/result', t,
        jsonb_build_object('result_id', t), repeat('a', 64)
    );
    INSERT INTO integration.exchange_transactions (
        exchange_id, event_id, source_system, source_result_id, source_payload, source_hash
    ) VALUES (
        exchange_2, gen_random_uuid(), 'https://example.org/lis/result', t || '_other',
        '{}'::jsonb, repeat('b', 64)
    );

    BEGIN
        INSERT INTO integration.exchange_transactions (
            exchange_id, event_id, source_system, source_result_id, source_payload, source_hash
        ) VALUES (
            gen_random_uuid(), event_1, 'https://example.org/other', t || '_new',
            '{}'::jsonb, repeat('c', 64)
        );
        RAISE EXCEPTION 'TEST FAILED: duplicate integration.event_id accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: Integration event_id UNIQUE';
    END;

    BEGIN
        INSERT INTO integration.exchange_transactions (
            exchange_id, event_id, source_system, source_result_id, source_payload, source_hash
        ) VALUES (
            gen_random_uuid(), gen_random_uuid(), 'https://example.org/lis/result', t,
            '{}'::jsonb, repeat('c', 64)
        );
        RAISE EXCEPTION 'TEST FAILED: duplicate integration source key accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: Integration (source_system, source_result_id) UNIQUE';
    END;

    INSERT INTO integration.exchange_attempts(attempt_id, exchange_id, attempt_no, phase)
    VALUES (attempt_1, exchange_1, 1, 'SEND'),
           (attempt_2, exchange_2, 1, 'VERIFY');

    BEGIN
        INSERT INTO integration.exchange_attempts(attempt_id, exchange_id, attempt_no, phase)
        VALUES (gen_random_uuid(), exchange_1, 1, 'SEND');
        RAISE EXCEPTION 'TEST FAILED: duplicate SEND attempt accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: Integration (exchange_id, phase, attempt_no) UNIQUE';
    END;

    -- Valid event with NULL attempt is allowed.
    INSERT INTO integration.exchange_events(log_event_id, exchange_id, event_type, attempt_id)
    VALUES (gen_random_uuid(), exchange_1, 'RECEIVED', NULL);

    -- An attempt from exchange_2 must not be attached to exchange_1's event.
    BEGIN
        INSERT INTO integration.exchange_events(log_event_id, exchange_id, event_type, attempt_id)
        VALUES (gen_random_uuid(), exchange_1, 'BAD_ATTEMPT_LINK', attempt_2);
        RAISE EXCEPTION 'TEST FAILED: cross-transaction attempt reference accepted';
    EXCEPTION WHEN foreign_key_violation THEN
        RAISE NOTICE 'PASS: Integration event attempt belongs to same exchange';
    END;

    -- Evaluator can keep a comparison without an exchange (e.g., LIS-side rejection).
    INSERT INTO integration.experiment_runs(
        run_id, scenario_id, protocol_version, manifest_hash, environment
    ) VALUES (run_1, 'SMOKE', 'smoke-test', repeat('d', 64), '{}'::jsonb);

    INSERT INTO integration.field_comparisons(
        comparison_id, run_id, case_id, exchange_id, rule_id, field_path, outcome
    ) VALUES (
        gen_random_uuid(), run_1, 'SMOKE-REJECTED', NULL, 'MR01', 'identifier', 'PASS'
    );
    RAISE NOTICE 'PASS: Integration field_comparisons.exchange_id permits NULL';

    RAISE NOTICE 'All smoke tests passed; temporary test data will be rolled back.';
END;
$smoke_tests$;
ROLLBACK;

-- ============================================================================
-- 5. VERIFICATION (read-only)
-- Expected table counts: lis = 5, integration = 5, emr = 3 (13 total).
-- Expected cross-system FK count: 0.
-- ============================================================================
SELECT table_schema AS schema_name, COUNT(*) AS table_count
FROM information_schema.tables
WHERE table_type = 'BASE TABLE'
  AND table_schema IN ('lis', 'integration', 'emr')
GROUP BY table_schema
ORDER BY table_schema;

SELECT COUNT(*) AS cross_schema_foreign_keys
FROM pg_constraint con
JOIN pg_class child_table ON child_table.oid = con.conrelid
JOIN pg_namespace child_schema ON child_schema.oid = child_table.relnamespace
JOIN pg_class parent_table ON parent_table.oid = con.confrelid
JOIN pg_namespace parent_schema ON parent_schema.oid = parent_table.relnamespace
WHERE con.contype = 'f'
  AND child_schema.nspname IN ('lis', 'integration', 'emr')
  AND parent_schema.nspname IN ('lis', 'integration', 'emr')
  AND child_schema.nspname <> parent_schema.nspname;
